// Derives the guide's colour tokens from the app's Tailwind theme (the glass role tokens), so the two
// can never drift and a fork that recolours the app recolours its guide for free.

type Block = Record<string, string>

function readBlock(css: string, opener: string): Block {
  const start = css.indexOf(opener)
  if (start === -1) return {}
  let depth = 0
  let end = start + opener.length - 1
  for (let i = end; i < css.length; i++) {
    if (css[i] === '{') depth++
    else if (css[i] === '}' && --depth === 0) {
      end = i
      break
    }
  }
  const block: Block = {}
  for (const match of css.slice(start, end).matchAll(/--color-([\w-]+)\s*:\s*([^;]+);/g)) {
    block[match[1]] = match[2].trim()
  }
  return block
}

export function parseThemeBlocks(css: string): { theme: Block; dark: Block } {
  const opener = css.includes('@theme static {') ? '@theme static {' : '@theme {'
  return { theme: readBlock(css, opener), dark: readBlock(css, '.dark {') }
}

// Follows `var(--color-x)` chains: the declaring block first, then @theme.
function resolve(name: string, block: Block, theme: Block): string | undefined {
  let value = block[name] ?? theme[name]
  for (let hops = 0; value?.startsWith('var(') && hops < 10; hops++) {
    const ref = /^var\(\s*--color-([\w-]+)\s*\)$/.exec(value)?.[1]
    value = ref ? (block[ref] ?? theme[ref]) : undefined
  }
  return value
}

// Which app block a role token is read from: the light theme or the .dark overrides.
type Source = ['light' | 'dark', string]
const light = (name: string): Source => ['light', name]
const dark = (name: string): Source => ['dark', name]

// Brand token -> app role token, in light and dark mode. Most follow their role in both modes. The
// guide's sidebar, hero and table headers stay dark chrome in light mode too, so the "chrome" tokens
// and the on-chrome text take the dark-theme value where the chrome needs a light tint on dark.
const BRAND_TOKENS: Record<string, { light: Source; dark: Source }> = {
  accent: { light: light('accent'), dark: dark('accent') },
  'accent-hover': { light: light('accent-hover'), dark: dark('accent-hover') },
  'accent-pressed': { light: light('accent-pressed'), dark: dark('accent-pressed') },
  'accent-soft': { light: light('accent-soft'), dark: dark('accent-soft') },
  'on-accent-soft': { light: light('on-accent-soft'), dark: dark('on-accent-soft') },
  // Filled controls carrying white text: the light-mode accent in both modes.
  'accent-fill': { light: light('accent'), dark: light('accent') },
  'accent-fill-hover': { light: light('accent-hover'), dark: light('accent-hover') },
  'accent-on-chrome': { light: dark('accent'), dark: dark('accent') },
  ink: { light: light('ink'), dark: dark('ink') },
  leaf: { light: light('leaf'), dark: dark('leaf') },
  success: { light: light('success'), dark: dark('success') },
  'success-soft': { light: light('success-soft'), dark: dark('success-soft') },
  page: { light: light('page'), dark: dark('page') },
  'panel-solid': { light: light('panel-solid'), dark: dark('panel-solid') },
  deep: { light: light('ink'), dark: dark('page') },
  chrome: { light: light('accent-pressed'), dark: dark('sunken') },
  'on-chrome': { light: dark('ink'), dark: dark('ink') },
  'on-chrome-muted': { light: dark('ink-muted'), dark: dark('ink-muted') },
}

export function generateBrandTokensCss(css: string): string {
  const { theme, dark: darkBlock } = parseThemeBlocks(css)
  const missing = new Set<string>()
  const read = ([mode, name]: Source): string | undefined => {
    const block = mode === 'light' ? theme : darkBlock
    const value = block[name] === undefined ? undefined : resolve(name, block, theme)
    if (!value || value.startsWith('var(')) {
      missing.add(`--color-${name}`)
      return undefined
    }
    return value
  }
  const lightLines: string[] = []
  const darkLines: string[] = []
  for (const [brand, source] of Object.entries(BRAND_TOKENS)) {
    lightLines.push(`  --brand-${brand}: ${read(source.light)};`)
    darkLines.push(`  --brand-${brand}: ${read(source.dark)};`)
  }
  if (missing.size > 0)
    throw new Error(`Missing tokens in tailwind.css: ${[...missing].join(', ')}`)
  return `/* Generated by scripts/sync-brand.ts from frontend/src/assets/styles/tailwind.css — do not edit. */\n:root {\n${lightLines.join('\n')}\n}\n\n.dark {\n${darkLines.join('\n')}\n}\n`
}
